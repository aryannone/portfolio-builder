from playwright.sync_api import sync_playwright
import json,sys
from h import APP
res=[]
def ok(name,cond,info=''):
    res.append((name,bool(cond),info)); print(('PASS ' if cond else 'FAIL ')+name, info if not cond else '')
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1300,'height':850},accept_downloads=True); pg=ctx.new_page()
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(APP); pg.wait_for_timeout(800)
    ok('landing back disabled', pg.is_disabled('.appbar .back'))
    pg.click('.l-cta [data-act=startnew]'); pg.wait_for_timeout(300)
    ok('route system', pg.evaluate('location.hash')=='#/new/system', pg.evaluate('location.hash'))
    ok('system back enabled', not pg.is_disabled('.appbar .back'))
    pg.click('.sysopt:nth-child(2)'); pg.fill('#wiz-name','My bold site'); pg.click('.stepbar [data-act=wiznext]'); pg.wait_for_timeout(600)
    ok('create project -> template step', pg.evaluate('location.hash')=='#/new/template' and pg.evaluate('PV.S.project.design.system')=='maximal')
    pg.click('.gcard:has-text("Neo-Experimental") [data-act=tplpick]'); pg.wait_for_timeout(300)
    ok('pick template', pg.evaluate('PV.S.project.design.template')=='neo-experimental')
    pg.click('.stepbar [data-act=next]'); pg.wait_for_timeout(500)
    ok('info step', pg.evaluate('location.hash')=='#/new/info')
    pg.fill('[data-bind="person/name"]','Priya Raman'); pg.wait_for_timeout(500)
    ok('name in model', pg.evaluate('PV.S.project.person.name')=='Priya Raman')
    fr=pg.frame_locator('#wizprev iframe'); ok('wizard preview shows name', fr.locator('.name').first.inner_text()=='Priya Raman')
    pg.click('.appbar .back'); pg.wait_for_timeout(400)
    ok('back to template keeps template', pg.evaluate('location.hash')=='#/new/template' and pg.evaluate('PV.S.project.design.template')=='neo-experimental', pg.evaluate('[location.hash,PV.S.project.design.template,PV.S.saveState]'))
    pg.evaluate('history.forward()'); pg.wait_for_timeout(500)
    ok('browser forward -> info w/ data', pg.evaluate('location.hash')=='#/new/info' and pg.input_value('[data-bind="person/name"]')=='Priya Raman')
    pg.click('.stepbar [data-act=next]'); pg.wait_for_timeout(400)
    pg.click('.addtype[data-type=services]'); pg.wait_for_timeout(300)
    ok('add section', pg.evaluate('PV.S.project.sections.some(s=>s.type=="services")'))
    pg.click('.srow:has-text("Education") [data-act=sectoggle]'); pg.wait_for_timeout(300)
    ok('hide section', pg.evaluate('PV.S.project.sections.find(s=>s.type=="education").visible')==False)
    pg.click('.stepbar [data-act=next]'); pg.wait_for_timeout(900)
    ok('customize step', pg.evaluate('location.hash')=='#/new/customize')
    pg.screenshot(path='customize.png')
    pg.click('.nextbtn'); pg.wait_for_timeout(1200)
    ok('editor step', pg.evaluate('location.hash')=='#/editor')
    pg.screenshot(path='editor.png')
    print('errs',errs)
    ctx.storage_state(path='state.json')
    b.close()
bad=[r for r in res if not r[1]]; print(len(res)-len(bad),'passed',len(bad),'failed')
